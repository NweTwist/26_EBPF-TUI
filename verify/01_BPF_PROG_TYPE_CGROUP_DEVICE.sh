#!/bin/bash
# ═══════════════════════════════════════════════════════════════
# Модуль 01: BPF_PROG_TYPE_CGROUP_DEVICE
# Назначение: фильтрация доступа к устройствам через cgroup
# Хук: cgroup/dev — перехватывает обращения к блочным/символьным устройствам
# Карта: dev_access_count (счётчик обращений)
# Карта: blocked_devices (хеш-таблица заблокированных major:minor)
# Ожидание: при обращении к /dev/* счётчик увеличивается
# ═══════════════════════════════════════════════════════════════

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "[VERIFY] Модуль: BPF_PROG_TYPE_CGROUP_DEVICE"
echo "[VERIFY] Функция: контроль доступа к устройствам в cgroup"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

echo ""
echo "[VERIFY] Действие 1: чтение /dev/null (символьное устройство 1:3)"
echo "[VERIFY] Ожидание: BPF-программа зафиксирует обращение, счётчик +1"
cat /dev/null > /dev/null 2>&1
echo "[VERIFY] Результат: обращение к /dev/null выполнено"

echo ""
echo "[VERIFY] Действие 2: чтение /dev/zero (символьное устройство 1:5)"
echo "[VERIFY] Ожидание: ещё одно обращение, счётчик +1"
head -c 1 /dev/zero > /dev/null 2>&1
echo "[VERIFY] Результат: обращение к /dev/zero выполнено"

echo ""
echo "[VERIFY] Действие 3: чтение /dev/urandom (символьное устройство 1:9)"
echo "[VERIFY] Ожидание: счётчик +1, доступ разрешён (не в blocked_devices)"
head -c 1 /dev/urandom > /dev/null 2>&1
echo "[VERIFY] Результат: обращение к /dev/urandom выполнено"

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "[VERIFY] Итог: 3 обращения к устройствам выполнены"
echo "[VERIFY] Проверьте в [RT] что dev_access_count увеличился на 3+"
echo "[VERIFY] Примечание: USB-блокировка проверяется вставкой накопителя"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
exit 0
