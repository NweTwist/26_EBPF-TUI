#!/bin/bash

# Скрипт для запуска eBPF-TUI проекта
# Автоматически собирает Rust приложение и запускает веб-интерфейс

set -e  # Остановка при ошибке

echo "=========================================="
echo "Запуск eBPF-TUI проекта"
echo "=========================================="

# Получаем директорию скрипта
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

# 1. Сборка Rust приложения
echo ""
echo "[1/5] Сборка Rust приложения..."
cargo build --release

if [ $? -eq 0 ]; then
    echo "✓ Rust приложение успешно собрано"
else
    echo "✗ Ошибка при сборке Rust приложения"
    exit 1
fi

# 2. Переход в директорию web
echo ""
echo "[2/5] Переход в директорию web..."
cd web

# 3. Деактивация текущего виртуального окружения (если активно)
if [ -n "$VIRTUAL_ENV" ]; then
    echo "[3/5] Деактивация текущего виртуального окружения..."
    deactivate 2>/dev/null || true
else
    echo "[3/5] Виртуальное окружение не активно"
fi

# 4. Удаление старого виртуального окружения и создание нового
echo ""
echo "[4/5] Настройка Python виртуального окружения..."
rm -rf .venv
python3 -m venv .venv

# Активация виртуального окружения
source .venv/bin/activate

# Установка зависимостей
echo "Установка Python зависимостей..."
python -m pip install --upgrade pip
python -m pip install -r requirements.txt

if [ $? -eq 0 ]; then
    echo "✓ Python зависимости установлены"
else
    echo "✗ Ошибка при установке зависимостей"
    exit 1
fi

# 5. Запуск веб-сервера
echo ""
echo "[5/5] Запуск веб-сервера..."
echo "=========================================="
echo "Сервер будет доступен по адресу:"
echo "http://0.0.0.0:8000"
echo "=========================================="
echo ""

python app.py --host 0.0.0.0 --port 8000
